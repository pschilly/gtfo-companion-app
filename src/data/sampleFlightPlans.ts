/**
 * Converts flight plan route points into DCS Route Tool Lua preset syntax
 */
export function formatFlightPlanToLuaPreset(plan: FlightPlanDetail): string {
  const theatre = plan.sortie?.name ? 'Persian Gulf' : 'Syria';
  const wpBlocks = plan.route_points
    .map((wp, idx) => {
      const luaIdx = idx + 1;
      const altMeters = Math.round(wp.alt * 0.3048);
      const speedMps = Number((wp.speed * 0.514444).toFixed(2));
      // Approximate flat map projection for DCS coordinates if not explicit
      const xCoord = Math.round(wp.lat * 10000);
      const yCoord = Math.round(wp.lng * 10000);
      return [
        `        [${luaIdx}] = `,
        `        {`,
        `            ["alt"] = ${altMeters},`,
        `            ["alt_type"] = "BARO",`,
        `            ["name"] = "${wp.name}",`,
        `            ["speed"] = ${speedMps},`,
        `            ["type"] = "Turning Point",`,
        `            ["action"] = "${wp.action || 'Turning Point'}",`,
        `            ["x"] = ${xCoord},`,
        `            ["y"] = ${yCoord},`,
        `        }, -- end of [${luaIdx}]`,
      ].join('\n');
    })
    .join('\n');

  return [
    `["${plan.callsign}"] = `,
    `{`,
    `${wpBlocks}`,
    `}, -- end of ["${plan.callsign}"]`,
  ].join('\n');
}

/**
 * Builds DTC JSON structure for .dtc export
 */
export function buildDtcJsonPayload(plan: FlightPlanDetail): Record<string, unknown> {
  return {
    version: '1.2',
    aircraft: plan.airframe?.dcs_entity || 'FA-18C_hornet',
    callsign: plan.callsign,
    flight_plan_id: plan.identifier,
    created_at: new Date().toISOString(),
    radio_presets: [
      {
        radio: 'COMM1',
        channels: plan.comms_ladder
          ? (Array.isArray(plan.comms_ladder) ? plan.comms_ladder : []).map((c: any, i: number) => ({
              channel: c.channel || i + 1,
              frequency: c.frequency,
              name: c.label || c.name || `CH ${i + 1}`,
            }))
          : [],
      },
    ],
    waypoints: plan.route_points.map((wp) => ({
      index: wp.index,
      name: wp.name,
      lat: wp.lat,
      lng: wp.lng,
      alt_feet: wp.alt,
      speed_knots: wp.speed,
      mgrs: wp.mgrs,
      notes: wp.remarks,
    })),
    mids: plan.mids_settings || {},
    cmds: plan.cmds_settings || {},
  };
}
